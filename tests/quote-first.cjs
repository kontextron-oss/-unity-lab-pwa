'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('dashboard.js','utf8');
const start=source.indexOf('function unityReferenceQuoteItem(s){');
const end=source.indexOf('const unityPct=',start);
assert.ok(start>0&&end>start);
const points=[{date:'2026-10-29',close:100},{date:'2026-10-30',close:101}];
const item={isin:'US0079031078',providerSymbol:'AMD',currency:'USD',price:101,date:'2026-10-30',points};
const stock={isin:'US0079031078',providerSymbol:'AMD',currency:'USD',name:'AMD'};
const market={items:{[stock.isin]:item}};
const context={unityMarket:market,unityBusinessDaysSince:()=>1,stock};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
assert.equal(vm.runInContext('unityReferenceQuoteItem(stock)?.price',context),101);
assert.equal(vm.runInContext('unityReferenceQuoteItem({...stock,currency:"EUR"})',context),null);
item.date='2026-10-29';assert.equal(vm.runInContext('unityReferenceQuoteItem(stock)',context),null);
item.date='2026-10-30';item.price=999;assert.equal(vm.runInContext('unityReferenceQuoteItem(stock)',context),null);
item.price=101;item.isin='US0000000000';assert.equal(vm.runInContext('unityReferenceQuoteItem(stock)',context),null);
item.isin=stock.isin;
item.points=[...Array.from({length:198},(_,i)=>({date:'2025-01-'+String((i%28)+1).padStart(2,'0'),close:100})),...points];
assert.equal(vm.runInContext('unityReferenceQuoteItem(stock)',context),null);
console.log('Short-history quote validation, identity, currency and close-date integrity passed.');
